  .^gamma2).^(-1);0,eta(2).^(-1),eta(2).^((-1)+gamma2).*(eta(1) ...
  .^gamma2+eta(2).^gamma2).^(-1);(-1).*eta(1).^(-2),0,eta(1).^((-2)+ ...
  gamma2).*(eta(1).^gamma2+eta(2).^gamma2).^(-2).*((-1).*eta(1) ...
  .^gamma2+((-1)+gamma2).*eta(2).^gamma2);0,(-1).*eta(2).^(-2),eta( ...
  2).^((-2)+gamma2).*(((-1)+gamma2).*eta(1).^gamma2+(-1).*eta(2) ...
  .^gamma2).*(eta(1).^gamma2+eta(2).^gamma2).^(-2);0,0,(-1).* ...
  gamma2.*eta(1).^((-1)+gamma2).*eta(2).^((-1)+gamma2).*(eta(1) ...
  .^gamma2+eta(2).^gamma2).^(-2);2.*eta(1).^(-3),0,eta(1).^((-3)+ ...
  gamma2).*(eta(1).^gamma2+eta(2).^gamma2).^(-3).*(2.*eta(1).^(2.* ...
  gamma2)+(-1).*((-4)+3.*gamma2+gamma2.^2).*eta(1).^gamma2.*eta(2) ...
